"""Render reviewer-friendly Markdown risk reports."""

from __future__ import annotations

from typing import Any


def render_markdown_report(
    *,
    title: str,
    overall_risk: str,
    overall_score: float,
    operations: list[dict[str, Any]],
    findings: list[dict[str, Any]],
    dependency_graph: dict[str, Any],
    code_references: list[dict[str, Any]],
    rollout_plan: list[dict[str, Any]],
    rollback_sql: str,
    llm_explanation: str | None,
) -> str:
    lines = [
        f"# SchemaSentinel Risk Report — {title}",
        "",
        f"**Overall risk:** `{overall_risk}` · **Score:** `{overall_score:.2f}`",
        "",
        "> Analyzes database migrations as software changes with blast-radius reasoning.",
        "",
        "## Summary",
        "",
        f"- Operations parsed: **{len(operations)}**",
        f"- Risk findings: **{len(findings)}**",
        f"- Code references: **{len(code_references)}**",
        f"- Graph nodes: **{dependency_graph.get('stats', {}).get('node_count', 0)}**",
        "",
        "## Parsed operations",
        "",
        "| # | Type | Table | Column |",
        "|---|------|-------|--------|",
    ]
    for i, op in enumerate(operations, start=1):
        lines.append(
            f"| {i} | `{op.get('op_type')}` | `{op.get('table') or '—'}` | `{op.get('column') or '—'}` |"
        )

    lines.extend(["", "## Deterministic risk findings", ""])
    if not findings:
        lines.append("_No findings._")
    for f in findings:
        rev = "reversible" if f.get("reversible", True) else "**irreversible**"
        lines.extend(
            [
                f"### [{f.get('severity', '?').upper()}] {f.get('title')} (`{f.get('rule_id')}`)",
                "",
                f"- Category: `{f.get('category')}` · Score: `{f.get('score')}` · {rev}",
                f"- {f.get('message')}",
                "",
            ]
        )

    lines.extend(["", "## Blast radius", ""])
    blast = dependency_graph.get("blast_radius") or {}
    if not blast:
        lines.append("_No table blast radius computed._")
    for table, info in blast.items():
        code_n = len(info.get("code_refs") or [])
        lines.append(f"- **`{table}`** — degree `{info.get('degree')}`, code refs `{code_n}`")

    lines.extend(["", "## Application references", ""])
    if not code_references:
        lines.append("_No code references found (provide `repo_path` or use a sample scenario)._")
    else:
        lines.append("| File | Line | Symbol | Endpoint hint |")
        lines.append("|------|------|--------|---------------|")
        for ref in code_references[:40]:
            lines.append(
                f"| `{ref.get('path')}` | {ref.get('line')} | `{ref.get('symbol')}` | "
                f"{ref.get('endpoint_hint') or '—'} |"
            )

    lines.extend(["", "## Phased rollout (expand → backfill → switch → contract)", ""])
    for step in rollout_plan:
        lines.append(f"### {step.get('phase', '').title()}: {step.get('title')}")
        lines.append("")
        lines.append(step.get("description") or "")
        lines.append("")
        for action in step.get("actions") or []:
            lines.append(f"- {action}")
        lines.append("")

    lines.extend(
        [
            "## Rollback sketch",
            "",
            "```sql",
            rollback_sql.strip(),
            "```",
            "",
        ]
    )

    if llm_explanation:
        lines.extend(["## LLM explanation", "", llm_explanation.strip(), ""])

    lines.extend(
        [
            "---",
            "_Generated by SchemaSentinel — deterministic rules first, LLM explanation second._",
        ]
    )
    return "\n".join(lines)
